// Builds the O2 evaluation dataset: 50 real, open notices for the 3 sample
// profiles, fetched live with the app's own TED and World Bank clients.
//
//   flutter test tool/eval/build_dataset_test.dart
//
// Writes eval/notices.json (the frozen dataset), eval/labels.csv (the
// sheet the team labels by hand) and integration_test/eval_data.dart (the
// same data embedded for the on-device harness). Not part of CI.
import 'dart:convert';
import 'dart:io';

import 'package:bidradar/core/net/resilient_http.dart';
import 'package:bidradar/data/models/models.dart';
import 'package:bidradar/data/seed/sample_companies.dart';
import 'package:bidradar/data/sources/ted_client.dart';
import 'package:bidradar/data/sources/tender_source.dart';
import 'package:bidradar/data/sources/worldbank_client.dart';
import 'package:flutter_test/flutter_test.dart';

/// How many notices per profile, and which sources to draw from.
const plan = {
  'sample-it-lanka': (17, [TenderSourceType.worldBank]),
  'sample-consult-eu': (17, [TenderSourceType.ted]),
  'sample-build-supply': (16, [TenderSourceType.worldBank]),
};

void main() {
  test('build eval dataset', () async {
    final samples = {
      for (final s in SampleCompanies.parse(
        File('assets/seed/sample_companies.json').readAsStringSync(),
      ))
        s.company.id: s,
    };
    final http = ResilientHttp();
    final sources = <TenderSourceType, TenderSource>{
      TenderSourceType.ted: TedClient(http),
      TenderSourceType.worldBank: WorldBankClient(http),
    };

    final items = <Map<String, Object?>>[];
    for (final MapEntry(key: id, value: (count, kinds)) in plan.entries) {
      final s = samples[id]!;
      final found = <Tender>[];
      for (final k in kinds) {
        found.addAll(
          await sources[k]!.search(
            TenderQuery.fromProfile(s.profile, limit: 60),
          ),
        );
      }
      // Thin markets (e.g. works in Sri Lanka and the Maldives) are topped
      // up from neighbouring countries. The rules should veto those on
      // country, which the evaluation also measures.
      if (found.where((t) => t.noticeText.length >= 300).length < count) {
        for (final k in kinds) {
          found.addAll(
            await sources[k]!.search(
              TenderQuery(
                cpvCodes: s.profile.cpvCodes,
                countries: const ['IND', 'BGD', 'NPL'],
                limit: 60,
              ),
            ),
          );
        }
      }
      // Real text only: drop notices too short to judge.
      final usable = found.where((t) => t.noticeText.length >= 300).toList()
        ..sort((a, b) => a.id.compareTo(b.id));
      // Served-country notices first, then the top-up.
      usable.sort(
        (a, b) => (s.profile.countries.contains(a.country) ? 0 : 1).compareTo(
          s.profile.countries.contains(b.country) ? 0 : 1,
        ),
      );
      final picked = usable.take(count).toList();
      expect(
        picked.length,
        count,
        reason: '$id: only ${usable.length} usable notices',
      );
      for (final t in picked) {
        items.add({'profile': id, 'tender': t.toJson()});
      }
    }
    http.close();

    final json = const JsonEncoder.withIndent(' ').convert({
      'builtAt': DateTime.now().toUtc().toIso8601String(),
      'note':
          'Real public notices from EU TED and the World Bank, frozen '
          'for the BidRadar evaluation. Profiles are synthetic.',
      'items': items,
    });
    File('eval/notices.json').writeAsStringSync(json);

    final csv = StringBuffer(
      'n,profile,tender_id,title,url,label,labeller,notes\n',
    );
    for (final (i, it) in items.indexed) {
      final t = it['tender']! as Map<String, Object?>;
      String q(Object? v) => '"${'${v ?? ''}'.replaceAll('"', '""')}"';
      csv.writeln(
        [
          i + 1,
          it['profile'],
          '${t['source']}_${t['sourceId']}',
          q(t['title']),
          q(t['url']),
          '', // BID / NO_BID / REVIEW, filled by a person
          '',
          '',
        ].join(','),
      );
    }
    File('eval/labels.csv').writeAsStringSync(csv.toString());

    File('integration_test/eval_data.dart').writeAsStringSync(
      '// GENERATED by tool/eval/build_dataset_test.dart. Do not edit.\n'
      '// Base64, because notice text contains characters such as a\n'
      '// dollar sign that would need escaping in a Dart string.\n'
      "const evalDatasetBase64 = '${base64Encode(utf8.encode(json))}';\n",
    );
    // ignore: avoid_print
    print('wrote ${items.length} notices');
  }, timeout: const Timeout(Duration(minutes: 5)));
}
